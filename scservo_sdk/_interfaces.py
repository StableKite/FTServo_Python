"""Structural contracts for genuine public replacement objects."""
from typing import Iterable, Optional, Protocol, Sequence, Union

class SyncWriter(Protocol):
    def clearParam(self) -> None: ...
    def addParam(self, scs_id: int, data: Sequence[int]) -> bool: ...
    def txPacket(self) -> int: ...

class PortStream(Protocol):
    def reset_input_buffer(self) -> None: ...
    def read(self, length: int, /) -> bytes: ...
    def write(self, value: Sequence[int], /) -> int: ...


class PacketPort(Protocol):
    """Minimum transport used by packet handlers, independent of serial ownership.

    Packet construction uses integer lists; the public mutable-packet primitive
    also accepts bytearray. Reads are extended into an integer byte buffer.
    Timeout lengths are integers. None from a short/unavailable write remains a
    real transmission failure, as with the original PortHandler.
    """

    is_using: bool

    def clearPort(self) -> None: ...
    def readPort(self, length: int, /) -> Iterable[int]: ...
    def writePort(self, packet: Union[list[int], bytearray], /) -> Optional[int]: ...
    def setPacketTimeout(self, packet_length: int, /) -> None: ...
    def isPacketTimeout(self) -> bool: ...
